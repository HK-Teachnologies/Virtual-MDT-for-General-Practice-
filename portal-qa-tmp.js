function envVal(key) {
  const env = fs.readFileSync(COMPOSE + '\\.env', 'utf8');
  const line = env.split(/\r?\n/).find((l) => l.startsWith(key + '='));
  return line.slice(key.length + 1).trim();
}
function latestOtp() {
  const logs = execSync('docker compose logs backend --no-log-prefix', { cwd: COMPOSE, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const lines = logs.split('\n').filter((l) => l.includes('OTP for ' + EMAIL));
  const m = lines[lines.length - 1].match(/: (\d{6})/);
  return m && m[1];
}
